import { mkdir, readdir, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'

const projectRoot = process.cwd()
const publicRoot = path.join(projectRoot, 'public')
const outputFile = path.join(projectRoot, 'src', 'data', 'local-media-assets.js')

const imageExtensions = new Set([
  '.jpg',
  '.jpeg',
  '.png',
  '.webp',
  '.gif',
  '.avif',
  '.svg',
])

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const files = []

  for (const entry of entries) {
    const absolute = path.join(directory, entry.name)

    if (entry.isDirectory()) {
      files.push(...(await walk(absolute)))
      continue
    }

    if (!entry.isFile()) continue

    const extension = path.extname(entry.name).toLowerCase()
    if (!imageExtensions.has(extension)) continue

    files.push(absolute)
  }

  return files
}

function toPublicUrl(absolutePath) {
  const relative = path.relative(publicRoot, absolutePath)
  const segments = relative.split(path.sep).map(encodeURIComponent)
  return `/${segments.join('/')}`
}

let localFiles = []

try {
  localFiles = await walk(publicRoot)
} catch {
  localFiles = []
}

const assets = []

for (const absolute of localFiles) {
  const info = await stat(absolute)
  const relative = path.relative(publicRoot, absolute).split(path.sep).join('/')
  const url = toPublicUrl(absolute)

  assets.push({
    id: `local:${relative}`,
    public_id: `local:${relative}`,
    secure_url: url,
    resource_type: 'image',
    width: null,
    height: null,
    bytes: info.size,
    original_filename: relative,
    created_at: null,
    source: 'public',
    read_only: true,
  })
}

assets.sort((a, b) =>
  String(a.original_filename).localeCompare(String(b.original_filename)),
)

await mkdir(path.dirname(outputFile), { recursive: true })

await writeFile(
  outputFile,
  `// Auto-generated by scripts/generate-media-manifest.mjs\n` +
    `// Do not edit manually.\n` +
    `export const localMediaAssets = ${JSON.stringify(assets, null, 2)}\n`,
  'utf8',
)

console.log(`[media] Indexed ${assets.length} image(s) from public/.`)
